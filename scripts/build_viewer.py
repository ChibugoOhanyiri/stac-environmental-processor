"""M6: build the static evidence viewer's data (web/data/) from the STAC catalogue.

For each catalogue Item: a transparent PNG of the labels ('no change' is see-through) and copies of the
label COG and receipt for download; plus web/data/items.js with the metadata the page shows.
Runs offline. Open web/index.html in a browser afterwards (no server needed).
Usage: .venv/bin/python scripts/build_viewer.py
"""
import csv
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import rasterio

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import water  # noqa: E402

CAT, OUT = ROOT / "catalog", ROOT / "web/data"
RGBA = {water.NO_CHANGE: (0, 0, 0, 0), water.PERSISTENT_WATER: (40, 90, 200, 200),
        water.NEW_DARK_WATER: (0, 200, 220, 230), water.LAND_LOUDER: (220, 40, 40, 220),
        water.CANT_TELL: (250, 190, 0, 220), water.NOT_OBSERVED: (0, 0, 0, 160)}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    collection = json.loads((CAT / "collection.json").read_text(encoding="utf-8"))
    entries = []
    for link in collection["links"]:
        if link["rel"] != "item":
            continue
        item_path = (CAT / link["href"]).resolve()
        item = json.loads(item_path.read_text(encoding="utf-8"))
        with rasterio.open(item_path.parent / item["assets"]["labels"]["href"]) as f:
            labels = f.read(1)
        rgba = np.zeros((4, *labels.shape), dtype="uint8")
        for code, colour in RGBA.items():
            for i in range(4):
                rgba[i][labels == code] = colour[i]
        png = OUT / f"{item['id']}.png"
        with rasterio.open(png, "w", driver="PNG", width=labels.shape[1], height=labels.shape[0],
                           count=4, dtype="uint8") as dst:
            dst.write(rgba)
        shutil.copy(item_path.parent / item["assets"]["labels"]["href"], OUT / f"{item['id']}_labels.tif")
        receipt = (item_path.parent / item["assets"]["receipt"]["href"]).resolve()
        shutil.copy(receipt, OUT / f"{item['id']}_receipt.json")
        shutil.copy(item_path, OUT / f"{item['id']}_stac-item.json")
        p = item["properties"]
        counts = p["lekki:label_pixel_counts"]
        total = sum(counts.values())
        entries.append({"id": item["id"], "title": p["title"], "description": p["description"],
                        "datetime": p["datetime"], "role": p["lekki:role"], "bbox": item["bbox"],
                        "reference": p["lekki:reference_window"], "images": p["lekki:input_image_ids"],
                        "rules": {k: v for k, v in p["lekki:rules"].items() if k != "how_chosen"},
                        "pct": {k: round(100 * v / total, 2) for k, v in counts.items()},
                        "km2": {k: round(v * p["lekki:pixel_area_m2"] / 1e6, 3) for k, v in counts.items()},
                        "observed_pct": round(100 * (total - counts["not observed"]) / total, 2),
                        "run_id": p["lekki:run_id"], "commit": p["lekki:code_commit"], "claim": p["lekki:claim"],
                        "png": f"data/{png.name}", "cog": f"data/{item['id']}_labels.tif",
                        "receipt": f"data/{item['id']}_receipt.json", "stac": f"data/{item['id']}_stac-item.json"})
    entries.sort(key=lambda e: e["datetime"])
    places = [{"name": r["name"], "lat": float(r["lat"]), "lon": float(r["lon"]), "source": r["source"]}
              for r in csv.DictReader(open(ROOT / "evidence/places_osm_2026-11-07.csv", encoding="utf-8"))]
    js = ("// Generated by scripts/build_viewer.py from catalog/. Do not edit by hand.\n"
          f"window.ITEMS = {json.dumps(entries, indent=1)};\nwindow.PLACES = {json.dumps(places, indent=1)};\n"
          f"window.ATTRIBUTION = {json.dumps(collection['lekki:attribution'])};\n")
    (OUT / "items.js").write_text(js, encoding="utf-8")
    print(f"wrote {len(entries)} layers to {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
